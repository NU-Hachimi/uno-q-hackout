"""倾斜控制视角、摇杆转向的全部参数，都在这个文件里调。

改完后在 arcade/ 下运行 `flock /tmp/uno-q-board.lock make flash`，重新进游戏、在 Ready 画面按 A 就生效。

工作方式：在 Ready 画面按 A（或菜单里 Recalibrate）时记下掌机当时的姿势作为“中立”。
之后掌机相对中立倾斜超过死区才开始转视角，倾斜越大转得越快，回到中立就停（速率控制）。
摇杆左右让马转向，镜头跟着一起转；倾斜在此基础上再叠加视角（第 6 节）。
"""

# ---- 1. 轴向 -------------------------------------------------------------
# 掌机倾斜时，重力在 Movement 传感器的哪个轴上变化。写 "x"、"y"、"z"，前面加 "-" 表示反向。
# 不确定时把 DEBUG_LOG 设为 True，看日志里哪个轴的度数随倾斜变化。
YAW_AXIS = "x"     # 左右倾斜 → 左右转视角
PITCH_AXIS = "y"   # 掌机上沿远离你 / 靠近你 → 抬头 / 低头

# 轴向找对了但方向反了，就把对应的开关改成 True。
INVERT_YAW = True
INVERT_PITCH = False

# ---- 2. 灵敏度 -----------------------------------------------------------
DEAD_ZONE_DEG = 6          # 倾斜小于这个角度不转，避免手抖
FULL_DEG = 27              # 倾斜到这个角度达到最大转速
MAX_YAW_RATE_DEG = 60     # 左右最大转速，度/秒
MAX_PITCH_RATE_DEG = 40    # 上下最大转速，度/秒
CURVE = 2.0                # 响应曲线：1 = 线性；2 = 二次，刚过死区时更细腻

# ---- 3. 平滑 -------------------------------------------------------------
SMOOTHING = 0.5            # 0–1，每帧新读数的权重；越小越平滑，但反应越慢

# ---- 4. 视角俯仰范围 -----------------------------------------------------
MIN_PITCH_DEG = -20        # 最多低头多少度
MAX_PITCH_DEG = 35         # 最多抬头多少度
START_PITCH_DEG = -3       # 开局时的俯仰

# ---- 5. 调试 -------------------------------------------------------------
# True 时每 0.5 s 在 `make logs` 里打印：相对中立姿势，x/y/z 三个轴各偏了多少度，
# 以及当前的左右 / 上下转速。找轴向时打开，调好后关掉。
DEBUG_LOG = False

# ---- 6. 摇杆转向与镜头跟随 -------------------------------------------------
# 摇杆左右：马转向，镜头跟着转同样的角度（马在画面里的位置不变）。摇杆上下：前进 / 后退。
STEER_RATE_DEG = 100       # 摇杆打满时的转向速度，度/秒
REVERSE_FRACTION = 0.35    # 摇杆向下时后退，速度是前进的多少倍
# 骑行时如果一段时间没有倾斜，镜头慢慢转回马的正后方（像赛车游戏的追尾镜头）。
RECENTER_DELAY_S = 0.8     # 倾斜回到死区多久后开始回正
RECENTER_RATE = 1.5        # 回正快慢，每秒补上剩余角度的比例；0 = 关闭回正
