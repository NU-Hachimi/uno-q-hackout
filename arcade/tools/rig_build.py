#!/usr/bin/env python3
"""Turn assets/rigs/*.json into sketch/gen/, python/gen/ and the golden poses (api.md §5.1).

    python3 tools/rig_build.py          (run from arcade/; rewrites the generated files)
    python3 tools/rig_build.py --check  (exit 1 if the generated files are stale)

The golden file holds bone and slot transforms from python/rig.py; the C++ rig code must match
them within 1 cm (tests/cpp/rig_golden.sh).

python/gen/rigs.apak holds every rig in alia-engine's resource pack format (its docs/formats.md
type 3), written with its tools/alia_pack.py (ALIA_ENGINE points at the checkout, default
~/Projects/alia-engine); the engine evaluates the same poses in C++ (tests/test_alia.py).
"""

import argparse
import copy
import json
import os
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
sys.path.insert(0, str(ROOT / "python"))

import rig as rigmath  # noqa: E402
from collide import BODY, HOOKABLE, PART  # noqa: E402

sys.path.insert(0, os.path.join(os.environ.get("ALIA_ENGINE", os.path.expanduser("~/Projects/alia-engine")), "tools"))
from alia_pack import PackWriter  # noqa: E402

GOLDEN_PHASES = (0, 64, 128, 192, 255)
MAX_BONES, MAX_SLOTS, MAX_ANIMS, MAX_VARIANTS = 16, 32, 16, 4
SOLID_RIGS = {"moose"}  # what shots and the hook can hit; the PC's own rigs (horse, rider) collide with nothing
HEADER = "Generated by tools/rig_build.py from arcade/assets/rigs/. Do not edit."


def fail(message):
    sys.exit(f"rig_build: {message}")


def load_rig(path, mesh_ids):
    rig = json.loads(path.read_text())
    name = rig["name"]
    bones = rig["bones"]
    if len(bones) > MAX_BONES or len(rig["slots"]) > MAX_SLOTS or len(rig["anims"]) > MAX_ANIMS:
        fail(f"{name}: too many bones, slots or anims")
    index = {}
    for i, bone in enumerate(bones):
        parent = bone["parent"]
        if parent is not None and parent not in index:
            fail(f"{name}: bone {bone['name']} comes before its parent {parent}")
        bone["parent_index"] = -1 if parent is None else index[parent]
        bone["mesh_id"] = mesh_ids[bone["mesh"]] if bone.get("mesh") else 0xFF
        index[bone["name"]] = i
    for slot in rig["slots"]:
        if slot["bone"] not in index:
            fail(f"{name}: slot bone {slot['bone']} is not a bone")
        if slot["variants"][0] is not None or len(slot["variants"]) > MAX_VARIANTS:
            fail(f"{name}: slot variants must start with null and have at most {MAX_VARIANTS} entries")
        slot["bone_index"] = index[slot["bone"]]
        slot["variant_mesh_ids"] = [0xFF] + [mesh_ids[v] for v in slot["variants"][1:]]
        slot.setdefault("rot", [0, 0, 0])
    for point, attach in rig.get("attach", {}).items():
        if attach["bone"] not in index:
            fail(f"{name}: attach {point} bone {attach['bone']} is not a bone")
        attach["bone_index"] = index[attach["bone"]]
    anims = sorted(rig["anims"], key=lambda a: a["id"])
    if [a["id"] for a in anims] != list(range(len(anims))):
        fail(f"{name}: animation ids must be 0..n-1")
    for anim in anims:
        for bone, track in anim["tracks"].items():
            if bone not in index or len(track) != anim["keys"]:
                fail(f"{name}/{anim['name']}: track {bone} must name a bone and have {anim['keys']} keys")
        if anim.get("root_y") and len(anim["root_y"]) != anim["keys"]:
            fail(f"{name}/{anim['name']}: root_y must have {anim['keys']} keys")
        for event in anim.get("events", []):
            if "bone" in event:
                event["bone_index"] = index[event["bone"]]
    rig["anims"] = anims
    return rig


def f(v):
    return f"{float(v):.4f}f"


def c_header(rig):
    name = rig["name"]
    out = [f"// {HEADER}", "#pragma once", "", '#include "rig_types.h"', "", "namespace gen {", ""]
    for anim in rig["anims"]:
        prefix = f"{name}_a{anim['id']}"
        for bone in rig["bones"]:
            track = anim["tracks"].get(bone["name"])
            if track:
                values = ", ".join(f(v) for key in track for v in key)
                out.append(f"static const float {prefix}_{bone['name']}[] = {{{values}}};")
        if anim.get("root_y"):
            out.append(f"static const float {prefix}_root_y[] = {{{', '.join(f(v) for v in anim['root_y'])}}};")
        tracks = ", ".join(f"{prefix}_{b['name']}" if b["name"] in anim["tracks"] else "nullptr" for b in rig["bones"])
        out.append(f"static const float* const {prefix}_tracks[] = {{{tracks}}};")
        out.append("")
    out.append(f"static const RigBone {name}_bones[] = {{")
    for bone in rig["bones"]:
        offset = ", ".join(f(v) for v in bone["offset"])
        out.append(f"    {{{bone['parent_index']}, {{{offset}}}, {bone['mesh_id']}}},  // {bone['name']}")
    out.append("};")
    out.append(f"static const RigAnim {name}_anims[] = {{")
    for anim in rig["anims"]:
        prefix = f"{name}_a{anim['id']}"
        root_y = f"{prefix}_root_y" if anim.get("root_y") else "nullptr"
        out.append(f"    {{{1 if anim['loop'] else 0}, {anim['keys']}, {root_y}, {prefix}_tracks}},  // {anim['name']}")
    out.append("};")
    out.append(f"static const RigSlot {name}_slots[] = {{")
    for slot in rig["slots"]:
        variants = slot["variant_mesh_ids"] + [0xFF] * (MAX_VARIANTS - len(slot["variant_mesh_ids"]))
        out.append(f"    {{{slot['bone_index']}, {{{', '.join(f(v) for v in slot['offset'])}}}, "
                   f"{{{', '.join(f(v) for v in slot['rot'])}}}, {len(slot['variant_mesh_ids'])}, "
                   f"{{{', '.join(str(v) for v in variants)}}}}},  // {slot['bone']} {'/'.join(slot.get('tags', []))}")
    out.append("};")
    attach = rig.get("attach", {})
    out.append(f"static const RigAttach {name}_attach[] = {{")
    for point, a in attach.items():
        out.append(f"    {{{a['bone_index']}, {{{', '.join(f(v) for v in a['offset'])}}}}},  // {point}")
    out.append("};")
    for i, point in enumerate(attach):
        out.append(f"constexpr uint8_t RIG_{name.upper()}_{point.upper()} = {i};  // attach index")
    out.append(f"static const Rig RIG_{name.upper()} = {{{len(rig['bones'])}, {name}_bones, {len(rig['anims'])}, "
               f"{name}_anims, {len(rig['slots'])}, {name}_slots, {len(attach)}, {name}_attach}};")
    out += ["", "}  // namespace gen", ""]
    return "\n".join(out)


TYPES_H = f"""// {HEADER}
#pragma once

#include <stdint.h>

namespace gen {{

struct RigBone {{
  int8_t parent;     // index of the parent bone, -1 for the root
  float offset[3];   // joint position in the parent's frame, m
  uint8_t mesh;      // mesh id (gen/meshes.h), 0xFF for none
}};

struct RigAnim {{
  uint8_t loop, keys;
  const float* rootY;           // keys values added to the root offset's y, or nullptr
  const float* const* tracks;   // per bone: keys x (rx, ry, rz) degrees, or nullptr (rest pose)
}};

struct RigSlot {{
  uint8_t bone;
  float offset[3];        // in the bone's frame, m
  float rot[3];           // rx, ry, rz degrees, R = Ry * Rx * Rz
  uint8_t nVariants;      // including variant 0 (empty)
  uint8_t variantMesh[{MAX_VARIANTS}];  // mesh id per variant; [0] is 0xFF
}};

struct RigAttach {{
  uint8_t bone;
  float offset[3];  // in the bone's frame, m
}};

struct Rig {{
  uint8_t nBones;
  const RigBone* bones;
  uint8_t nAnims;
  const RigAnim* anims;
  uint8_t nSlots;
  const RigSlot* slots;
  uint8_t nAttach;
  const RigAttach* attach;  // named points (rig JSON attach), indexed by RIG_<RIG>_<POINT>
}};

}}  // namespace gen
"""


def golden(rig):
    data = {"rig": rig["name"], "id": rig["id"], "phases": list(GOLDEN_PHASES),
            "note": "Rig-space bone and slot transforms from python/rig.py: origin, then +X/+Y/+Z unit points.",
            "anims": []}
    for anim in rig["anims"]:
        entry = {"id": anim["id"], "name": anim["name"], "poses": []}
        for phase in GOLDEN_PHASES:
            poses = rigmath.pose(rig, anim["id"], phase)
            mats = list(poses) + [rigmath.slot_matrix(rig, poses, s) for s in range(len(rig["slots"]))]
            points = []
            for m in mats:
                pts = [rigmath.transform(m, p) for p in ((0, 0, 0), (1, 0, 0), (0, 1, 0), (0, 0, 1))]
                points.append([round(c, 5) for p in pts for c in p])
            entry["poses"].append(points)
        data["anims"].append(entry)
    return json.dumps(data, indent=1) + "\n"


def engine_rig(rig):
    """The rig for alia-engine, its colliders tagged with Megalith's categories as layers (python/collide.py)."""
    rig = copy.deepcopy(rig)
    solid = rig["name"] in SOLID_RIGS
    for index, bone in enumerate(rig["bones"]):
        for c in bone.get("colliders", []):
            c.update(layers=(BODY | (HOOKABLE if c.get("hookable") else 0)) if solid else 0, user=index)
    for index, slot in enumerate(rig["slots"]):
        if slot.get("collider"):
            slot["collider"].update(layers=PART if solid else 0, user=index, priority=1)
    return rig


def build():
    mesh_ids = {m["name"]: m["id"] for m in json.loads((ASSETS / "meshes.json").read_text())["meshes"]}
    rigs = sorted((load_rig(p, mesh_ids) for p in (ASSETS / "rigs").glob("*.json")), key=lambda r: r["id"])
    if not rigs or rigs[0]["id"] < 1 or len({r["id"] for r in rigs}) != len(rigs):
        fail("rig ids must be unique and start at 1 (0 means no rig)")
    outputs = {ROOT / "sketch" / "gen" / "rig_types.h": TYPES_H}
    table = ["nullptr"] * (rigs[-1]["id"] + 1)
    includes = []
    for rig in rigs:
        name = rig["name"]
        outputs[ROOT / "sketch" / "gen" / f"rig_{name}.h"] = c_header(rig)
        includes.append(f'#include "rig_{name}.h"')
        table[rig["id"]] = f"&RIG_{name.upper()}"
        keep = {k: v for k, v in rig.items()}
        outputs[ROOT / "python" / "gen" / f"rig_{name}.py"] = (
            f'"""{HEADER}"""\n\nRIG = ' + pprint.pformat(keep, width=110, sort_dicts=False) + "\n")
        outputs[ROOT / "tests" / "golden" / f"rig_{name}.json"] = golden(rig)
    outputs[ROOT / "sketch" / "gen" / "rigs.h"] = "\n".join(
        [f"// {HEADER}", "#pragma once", ""] + includes +
        ["", "namespace gen {", f"constexpr int RIG_COUNT = {len(table)};",
         f"static const Rig* const RIGS[RIG_COUNT] = {{{', '.join(table)}}};  // index = rig_id", "}  // namespace gen", ""])
    pack = PackWriter()
    for rig in rigs:
        pack.add_rig(rig["name"], engine_rig(rig))  # the engine keeps what it uses (no hp, tags)
    outputs[ROOT / "python" / "gen" / "rigs.apak"] = pack.bytes()
    outputs[ROOT / "python" / "gen" / "rigs.py"] = "\n".join(
        [f'"""{HEADER}"""', ""] + [f"from gen.rig_{r['name']} import RIG as {r['name'].upper()}" for r in rigs] +
        ["", "RIGS = {" + ", ".join(f"{r['id']}: {r['name'].upper()}" for r in rigs) + "}", ""])
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only report whether the outputs are up to date")
    args = parser.parse_args()
    stale = []
    for path, data in build().items():
        binary = isinstance(data, bytes)
        if not path.exists() or (path.read_bytes() if binary else path.read_text()) != data:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data) if binary else path.write_text(data)
    for path in stale:
        print(("stale: " if args.check else "wrote: ") + str(path.relative_to(ROOT)))
    if args.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
